// Regenerates supabase/migrations/*_reference_data.sql from the engine's cards and jobs.
import { writeFileSync } from 'node:fs';
import { CARDS, JOBS } from '../supabase/functions/_shared/engine.js';
const q = v => v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`;
const j = v => v === null || v === undefined ? 'null' : `${q(JSON.stringify(v))}::jsonb`;
const arr = a => `array[${a.map(q).join(', ')}]::text[]`;
let sql = '-- Generated by scripts/gen-reference-sql.mjs — do not edit by hand.\n';
sql += 'delete from public.card_definitions;\ndelete from public.job_definitions;\n';
sql += 'insert into public.card_definitions (id, category, title, description, effects, choices) values\n';
sql += Object.values(CARDS).map(c => `  (${q(c.id)}, ${q(c.deck)}, ${q(c.title)}, ${q(c.desc)}, ${j(c.fx || [])}, ${j(c.ch)})`).join(',\n') + ';\n';
sql += 'insert into public.job_definitions (id, name, salary_m, pros, cons, data) values\n';
sql += Object.entries(JOBS).map(([k, c]) => `  (${q(k)}, ${q(c.name)}, ${c.sal}, ${arr(c.pros)}, ${arr(c.cons)}, ${j(c)})`).join(',\n') + ';\n';
writeFileSync(new URL('../supabase/migrations/20261027000100_reference_data.sql', import.meta.url), sql);
console.log(`Wrote ${Object.keys(CARDS).length} cards and ${Object.keys(JOBS).length} jobs.`);
